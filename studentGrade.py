score = int(input("Enter the student marks\n"))
if score >= 90:
    print("Student mark:", score , "Grade is A")
elif score >= 80:
    print("Student mark:", score , "Grade is B")
elif score >= 70:
    print("Student mark:", score , "Grade is C")
elif score >= 60:
    print("Student mark:", score , "Grade is D")
elif score >= 50:
    print("Student mark:", score , "Grade is E")
else:
    print("Student mark:", score , "Grade is F")


    